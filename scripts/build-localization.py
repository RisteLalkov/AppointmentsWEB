"""Build/check the browser copy of the shared English interface catalogue."""
import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'src/Appointments.Core/Localization/en.json'
target = root / 'src/Appointments.Web/wwwroot/i18n/en.js'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate translation: {key}')
        if not key or key != key.strip() or not isinstance(value, str) or not value:
            raise ValueError(f'Invalid translation: {key}')
        if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', value)):
            raise ValueError(f'Translation placeholders differ: {key}')
        result[key] = value
    return result

catalogue = json.loads(source.read_text(encoding='utf-8'), object_pairs_hook=unique)
content = '// Generated by scripts/build-localization.py from the shared Core catalogue.\nwindow.MedTerminEnglish = ' + json.dumps(catalogue, ensure_ascii=False, separators=(',', ':')) + ';\n'
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        raise SystemExit('English browser catalogue is outdated. Run python scripts/build-localization.py.')
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding='utf-8')
print(f'English catalogue: {len(catalogue)} messages; browser copy verified.' if args.check else f'Generated {target.relative_to(root)} ({len(catalogue)} messages).')
