import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
const dom = new JSDOM('<!doctype html><form><label for="current">Тековна лозинка</label><input id="current" name="CurrentPassword" type="password" autocomplete="current-password" required><label for="new">Нова лозинка</label><input id="new" name="NewPassword" type="password" autocomplete="new-password" minlength="12" required><button type="submit">Зачувај</button></form>', {runScripts:'outside-only',url:'http://localhost/'});
const w=dom.window, d=w.document;
let count=0;
const check=(ok,label)=>{if(!ok)throw Error(label);count++;console.log('PASS password '+label);};
try {
  w.eval(await readFile(new URL('../../src/Appointments.Web/wwwroot/js/password-visibility.js',import.meta.url),'utf8'));
  const current=d.querySelector('#current'), next=d.querySelector('#new');
  const toggle=input=>input.parentElement.querySelector('button');
  check(d.querySelectorAll('.password-visibility-toggle').length===2,'Every password gets exactly one toggle');
  check(current.type==='password' && next.type==='password','Passwords are hidden initially');
  current.value='Example-test-password';next.value='Another-test-password';
  let submits=0;d.querySelector('form').addEventListener('submit',e=>{e.preventDefault();submits++;});
  toggle(current).click();
  check(current.type==='text' && next.type==='password','Reveal affects only the chosen field');
  check(toggle(current).getAttribute('aria-pressed')==='true' && toggle(current).getAttribute('aria-label').startsWith('Сокриј лозинка'),'Accessible label and state describe hiding');
  check(toggle(current).getAttribute('aria-controls')==='current' && submits===0,'Toggle targets its field and never submits');
  toggle(current).click();
  check(current.type==='password' && toggle(current).getAttribute('aria-pressed')==='false','Second click masks the password');
  check(current.value==='Example-test-password' && current.name==='CurrentPassword' && current.autocomplete==='current-password','Value, field name and autofill semantics remain intact');
  check(next.minLength===12 && next.required,'Password constraints are preserved');
  toggle(current).click();toggle(next).click();
  const before=new w.FormData(d.querySelector('form'));
  d.querySelector('form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  check(current.type==='password' && next.type==='password','Submitting re-hides every revealed field');
  check(before.get('CurrentPassword')===new w.FormData(d.querySelector('form')).get('CurrentPassword') && submits===1,'Submission values are unchanged');
  toggle(current).click();d.querySelector('form').reset();
  check(current.type==='password','Form reset restores hidden state');
  toggle(next).click();w.dispatchEvent(new w.Event('pageshow'));
  check(next.type==='password','Restoring a page masks passwords');
  const extra=d.createElement('input');extra.type='password';extra.name='ExtraPassword';d.querySelector('form').append(extra);
  await new Promise(r=>w.setTimeout(r,0));
  check(extra.id && toggle(extra).getAttribute('aria-controls')===extra.id,'Dynamically added fields get a unique linked toggle');
  check(d.querySelectorAll('.password-visibility-toggle').length===3,'Mutation handling does not duplicate controls');
  extra.disabled=true;toggle(extra).click();
  check(extra.type==='password','Disabled fields cannot be revealed');
  check(!d.documentElement.outerHTML.includes('Example-test-password'),'Password value is not copied into rendered markup');
  console.log(`\n${count}/${count} password visibility checks passed.`);
} finally {w.close();}
